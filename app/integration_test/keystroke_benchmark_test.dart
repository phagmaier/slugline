// The §1.3 keystroke budget, on the 120-page reference script.
//
//     flutter test integration_test/keystroke_benchmark_test.dart -d linux
//
// The number that decides whether the editor can keep up is the frame **build**
// time, not the wall clock: wall clock is quantised to vsync, so 16.7 ms on a
// 60 Hz display is the floor rather than a cost. ADR 0005 chose this editor
// design on exactly that measurement, and this is where the choice keeps being
// checked.

import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter/scheduler.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';

import 'package:slugline/core/core.dart';
import 'package:slugline/core/document_core.dart';
import 'package:slugline/editor/editor_controller.dart';
import 'package:slugline/editor/editor_surface.dart';

/// §1.3.
const keystrokeBudgetMs = 16.0;
const openBudgetMs = 250.0;

void main() {
  final binding = IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  setUpAll(() async {
    await Core.init();
  });

  testWidgets('keystroke to frame stays inside the budget on 120 pages',
      (tester) async {
    // `flutter test` runs with the Flutter project as the working directory.
    final file = File('../testdata/reference-feature.fountain');
    expect(file.existsSync(), isTrue,
        reason: 'the reference script is generated by tools/make_reference.py');
    final script = file.readAsStringSync();

    final openWatch = Stopwatch()..start();
    final controller = EditorController(RustDocumentCore.parse(script));
    addTearDown(controller.dispose);
    final openMs = openWatch.elapsedMicroseconds / 1000;

    await tester.pumpWidget(MaterialApp(
      home: Scaffold(body: EditorSurface(controller: controller)),
    ));
    await tester.tap(find.byType(EditorSurface));
    await tester.pumpAndSettle();

    // Type into the middle of the script, so the measurement includes a
    // scrolled viewport and a realistic amount of document either side.
    final middle = controller.blocks[controller.blocks.length ~/ 2];
    controller.setSelection(DocSelection(
      anchor: DocPosition(block: middle.id, offsetUtf16: 0),
      focus: DocPosition(block: middle.id, offsetUtf16: 0),
    ));
    await tester.pumpAndSettle();

    final frames = <FrameTiming>[];
    final commandMs = <double>[];
    void collect(List<FrameTiming> timings) => frames.addAll(timings);
    binding.addTimingsCallback(collect);
    var collecting = true;
    void stopCollecting() {
      if (!collecting) return;
      collecting = false;
      binding.removeTimingsCallback(collect);
    }

    addTearDown(stopCollecting);

    const typed = 'The quick brown fox jumps over the lazy dog. ';
    for (var pass = 0; pass < 6; pass++) {
      for (final character in typed.split('')) {
        final watch = Stopwatch()..start();
        controller.insertText(character);
        commandMs.add(watch.elapsedMicroseconds / 1000);
        await tester.pump();
      }
    }
    await tester.pumpAndSettle();
    stopCollecting();

    final builds = [
      for (final frame in frames) frame.buildDuration.inMicroseconds / 1000,
    ];
    final rasters = [
      for (final frame in frames) frame.rasterDuration.inMicroseconds / 1000,
    ];

    _report(
      blocks: controller.blocks.length,
      rows: controller.layout.totalRows,
      openMs: openMs,
      commandMs: commandMs,
      builds: builds,
      rasters: rasters,
    );

    expect(openMs, lessThan(openBudgetMs),
        reason: 'open a 120-page script → editable (§1.3)');
    expect(_percentile(commandMs, 0.99), lessThan(keystrokeBudgetMs),
        reason: 'a keystroke must reach the core and come back inside a frame');
    expect(frames, isNotEmpty,
        reason: 'no frame timings arrived — run this on a device (-d linux)');
    expect(_percentile(builds, 0.99), lessThan(keystrokeBudgetMs),
        reason: 'keystroke → glyph on screen, p99 (§1.3)');
  });
}

double _percentile(List<double> values, double fraction) {
  if (values.isEmpty) return double.nan;
  final sorted = [...values]..sort();
  return sorted[((sorted.length - 1) * fraction).round()];
}

String _row(String label, List<double> values) =>
    '${label.padRight(24)}${values.length.toString().padLeft(5)}  '
    '${_percentile(values, 0.50).toStringAsFixed(2).padLeft(8)}  '
    '${_percentile(values, 0.99).toStringAsFixed(2).padLeft(8)}  '
    '${_percentile(values, 1.0).toStringAsFixed(2).padLeft(8)}';

void _report({
  required int blocks,
  required int rows,
  required double openMs,
  required List<double> commandMs,
  required List<double> builds,
  required List<double> rasters,
}) {
  final over = builds.where((build) => build > keystrokeBudgetMs).length;
  final buffer = StringBuffer()
    ..writeln('')
    ..writeln('=== PHASE 2 KEYSTROKE BUDGET (§1.3) ===')
    ..writeln('reference script: $blocks blocks, $rows rows')
    ..writeln('open → editable:  ${openMs.toStringAsFixed(1)} ms '
        '(budget ${openBudgetMs.toStringAsFixed(0)} ms)')
    ..writeln('')
    ..writeln('milliseconds             n       p50       p99       max')
    ..writeln('-' * 58)
    ..writeln(_row('keystroke → patched', commandMs))
    ..writeln(_row('frame build', builds))
    ..writeln(_row('frame raster', rasters))
    ..writeln('-' * 58)
    ..writeln('builds over ${keystrokeBudgetMs.toStringAsFixed(0)} ms: '
        '$over of ${builds.length}')
    ..writeln('=== END ===');
  // ignore: avoid_print — the point of this test is the table.
  print(buffer);
}
