// The §1.3 keystroke budget, on the 120-page reference script.
//
//     flutter test integration_test/keystroke_benchmark_test.dart -d linux
//
// The number that decides whether the editor can keep up is the frame **build**
// time, not the wall clock: wall clock is quantised to vsync, so 16.7 ms on a
// 60 Hz display is the floor rather than a cost. ADR 0005 chose this editor
// design on exactly that measurement, and this is where the choice keeps being
// checked.

import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter/scheduler.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';

import 'package:slugline/core/core.dart';
import 'package:slugline/core/document_core.dart';
import 'package:slugline/editor/editor_controller.dart';
import 'package:slugline/editor/editor_page.dart';
import 'package:slugline/editor/editor_surface.dart';
import 'package:slugline/editor/find_bar.dart';
import 'package:slugline/src/rust/api/files.dart' as files;

import 'managed_fixture.dart';

/// §1.3.
const keystrokeBudgetMs = 16.0;
const openBudgetMs = 250.0;

void main() {
  final binding = IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  late Directory root;
  late ManagedFixtures managed;

  setUpAll(() async {
    // A temporary XDG root, so that the journal this benchmark now writes goes
    // somewhere disposable rather than into the runner's own state directory.
    root = await Directory.systemTemp.createTemp('slugline-bench-');
    managed = ManagedFixtures(root);
    await Core.init(
      configDir: '${root.path}/config',
      dataDir: '${root.path}/data',
      stateDir: '${root.path}/state',
    );
  });

  tearDownAll(() async {
    await Core.instance.shutdown();
    if (root.existsSync()) await root.delete(recursive: true);
  });

  for (final usedFind in [false, true]) {
    testWidgets('keystroke to frame stays inside the budget on 120 pages, '
        'Find used=$usedFind', (tester) async {
      // `flutter test` runs with the Flutter project as the working directory.
      final file = File('../testdata/reference-feature.fountain');
      expect(
        file.existsSync(),
        isTrue,
        reason: 'the reference script is generated by tools/make_reference.py',
      );
      final script = file.readAsStringSync();

      final openWatch = Stopwatch()..start();
      final controller = EditorController(RustDocumentCore.parse(script));
      addTearDown(controller.dispose);
      final openMs = openWatch.elapsedMicroseconds / 1000;

      if (usedFind) await _useFind(tester, controller);
      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(body: EditorSurface(controller: controller)),
        ),
      );
      await tester.tap(find.byType(EditorSurface));
      await tester.pumpAndSettle();

      // Type into the middle of the script, so the measurement includes a
      // scrolled viewport and a realistic amount of document either side.
      final middle = controller.blocks[controller.blocks.length ~/ 2];
      controller.setSelection(
        DocSelection(
          anchor: DocPosition(block: middle.id, offsetUtf16: 0),
          focus: DocPosition(block: middle.id, offsetUtf16: 0),
        ),
      );
      await tester.pumpAndSettle();

      final frames = <FrameTiming>[];
      final commandMs = <double>[];
      void collect(List<FrameTiming> timings) => frames.addAll(timings);
      binding.addTimingsCallback(collect);
      var collecting = true;
      void stopCollecting() {
        if (!collecting) return;
        collecting = false;
        binding.removeTimingsCallback(collect);
      }

      addTearDown(stopCollecting);

      const typed = 'The quick brown fox jumps over the lazy dog. ';
      for (var pass = 0; pass < 6; pass++) {
        for (final character in typed.split('')) {
          final watch = Stopwatch()..start();
          controller.insertText(character);
          commandMs.add(watch.elapsedMicroseconds / 1000);
          await tester.pump();
        }
      }
      await tester.pumpAndSettle();
      stopCollecting();

      final builds = [
        for (final frame in frames) frame.buildDuration.inMicroseconds / 1000,
      ];
      final rasters = [
        for (final frame in frames) frame.rasterDuration.inMicroseconds / 1000,
      ];

      _report(
        usedFind: usedFind,
        blocks: controller.blocks.length,
        rows: controller.layout.totalRows,
        openMs: openMs,
        commandMs: commandMs,
        builds: builds,
        rasters: rasters,
      );

      expect(
        openMs,
        lessThan(openBudgetMs),
        reason: 'open a 120-page script → editable (§1.3)',
      );
      expect(
        _percentile(commandMs, 0.99),
        lessThan(keystrokeBudgetMs),
        reason: 'a keystroke must reach the core and come back inside a frame',
      );
      expect(
        frames,
        isNotEmpty,
        reason: 'no frame timings arrived — run this on a device (-d linux)',
      );
      expect(
        _percentile(builds, 0.99),
        lessThan(keystrokeBudgetMs),
        reason: 'keystroke → glyph on screen, p99 (§1.3)',
      );
    });

    testWidgets('the crash journal costs nothing the budget cannot afford, '
        'Find used=$usedFind', (tester) async {
      // Phase 4 put a `write(2)` on the keystroke path: every edit is appended to
      // the crash journal before it is answered. That is the whole reason a
      // `SIGKILL` loses nothing, and it is exactly the kind of thing that quietly
      // eats a frame budget — so it is measured, on the same script, against the
      // same number.
      //
      // The append is deliberately not `fsync`ed (see `storage/src/journal.rs`),
      // so what is being measured is a buffered write of a few hundred bytes.
      final reference = File('../testdata/reference-feature.fountain');
      // The library opens only a managed project (ADR 0068).
      final script = managed.path('benchmark-$usedFind.fountain');
      File(script).writeAsStringSync(reference.readAsStringSync());

      final handle = await files.libraryOpen(path: script);
      expect(handle, isNotNull);
      final core = RustDocumentCore.of(handle!);
      addTearDown(core.close);
      final controller = EditorController(core);
      addTearDown(controller.dispose);

      if (usedFind) await _useFind(tester, controller);
      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(body: EditorSurface(controller: controller)),
        ),
      );
      await tester.tap(find.byType(EditorSurface));
      await tester.pumpAndSettle();

      final middle = controller.blocks[controller.blocks.length ~/ 2];
      controller.setSelection(
        DocSelection(
          anchor: DocPosition(block: middle.id, offsetUtf16: 0),
          focus: DocPosition(block: middle.id, offsetUtf16: 0),
        ),
      );
      await tester.pumpAndSettle();

      final commandMs = <double>[];
      const typed = 'The quick brown fox jumps over the lazy dog. ';
      for (var pass = 0; pass < 6; pass++) {
        for (final character in typed.split('')) {
          final watch = Stopwatch()..start();
          controller.insertText(character);
          commandMs.add(watch.elapsedMicroseconds / 1000);
          await tester.pump();
        }
      }

      final (recorded, broken) = core.journalState;
      expect(broken, isFalse, reason: 'the journal kept up');
      expect(
        recorded,
        commandMs.length,
        reason:
            'one record per keystroke — nothing was skipped to make the number',
      );

      final buffer = StringBuffer()
        ..writeln('')
        ..writeln(
          '=== KEYSTROKE BUDGET WITH THE CRASH JOURNAL (§1.3, Find used=$usedFind) ===',
        )
        ..writeln('journal records written: $recorded')
        ..writeln('')
        ..writeln('milliseconds             n       p50       p99       max')
        ..writeln('-' * 58)
        ..writeln(_row('keystroke → journalled', commandMs))
        ..writeln('=== END ===');
      // ignore: avoid_print — the point of this test is the table.
      print(buffer);

      expect(
        _percentile(commandMs, 0.99),
        lessThan(keystrokeBudgetMs),
        reason: 'a journalled keystroke must still fit in a frame',
      );
    });
  }
}

/// Use Find and close it without clearing the query: Ctrl+G retains it.
Future<void> _useFind(WidgetTester tester, EditorController controller) async {
  // Exercise the real bar, then let the caller mount the same isolated surface
  // as the no-Find benchmark. Only retained search state differs between them.
  await tester.pumpWidget(
    MaterialApp(home: EditorPage(controller: controller)),
  );
  await tester.tap(find.byType(EditorSurface));
  await tester.pumpAndSettle();
  await tester.sendKeyDownEvent(LogicalKeyboardKey.controlLeft);
  await tester.sendKeyEvent(LogicalKeyboardKey.keyF);
  await tester.sendKeyUpEvent(LogicalKeyboardKey.controlLeft);
  await tester.pumpAndSettle();
  final field = find.ancestor(
    of: find.text('Find'),
    matching: find.byType(TextField),
  );
  await tester.enterText(field, 'the');
  await tester.pump(const Duration(milliseconds: 200));
  await tester.pumpAndSettle();
  expect(controller.selectedText()?.toLowerCase(), 'the');
  await tester.sendKeyEvent(LogicalKeyboardKey.escape);
  await tester.pumpAndSettle();
  expect(find.byType(FindBar), findsNothing);
  expect(controller.query.text, 'the');
}

double _percentile(List<double> values, double fraction) {
  if (values.isEmpty) return double.nan;
  final sorted = [...values]..sort();
  return sorted[((sorted.length - 1) * fraction).round()];
}

String _row(String label, List<double> values) =>
    '${label.padRight(24)}${values.length.toString().padLeft(5)}  '
    '${_percentile(values, 0.50).toStringAsFixed(2).padLeft(8)}  '
    '${_percentile(values, 0.99).toStringAsFixed(2).padLeft(8)}  '
    '${_percentile(values, 1.0).toStringAsFixed(2).padLeft(8)}';

void _report({
  required bool usedFind,
  required int blocks,
  required int rows,
  required double openMs,
  required List<double> commandMs,
  required List<double> builds,
  required List<double> rasters,
}) {
  final over = builds.where((build) => build > keystrokeBudgetMs).length;
  final buffer = StringBuffer()
    ..writeln('')
    ..writeln('=== KEYSTROKE BUDGET (§1.3, Find used=$usedFind) ===')
    ..writeln('reference script: $blocks blocks, $rows rows')
    ..writeln(
      'open → editable:  ${openMs.toStringAsFixed(1)} ms '
      '(budget ${openBudgetMs.toStringAsFixed(0)} ms)',
    )
    ..writeln('')
    ..writeln('milliseconds             n       p50       p99       max')
    ..writeln('-' * 58)
    ..writeln(_row('keystroke → patched', commandMs))
    ..writeln(_row('frame build', builds))
    ..writeln(_row('frame raster', rasters))
    ..writeln('-' * 58)
    ..writeln(
      'builds over ${keystrokeBudgetMs.toStringAsFixed(0)} ms: '
      '$over of ${builds.length}',
    )
    ..writeln('=== END ===');
  // ignore: avoid_print — the point of this test is the table.
  print(buffer);
}
